import { describe, expect, it } from 'vitest'
import { regionOf } from '../src/utils/region'

describe('regionOf', () => {
  it.each([
    ['서울특별시 중구 세종대로 110', '서울'],
    ['경기도 수원시 팔달구 효원로 1', '경기'],
    ['인천광역시 남동구 정각로 29', '인천'],
    ['강원특별자치도 춘천시 중앙로 1', '강원'],
    ['충청북도 청주시 상당구 상당로 82', '충북'],
    ['충청남도 홍성군 홍북읍 충남대로 21', '충남'],
    ['세종특별자치시 한누리대로 2130', '세종'],
    ['대전광역시 서구 둔산로 100', '대전'],
    ['전북특별자치도 전주시 완산구 효자로 225', '전북'],
    ['전라남도 무안군 삼향읍 오룡길 1', '전남'],
    ['광주광역시 서구 내방로 111', '광주'],
    ['경상북도 안동시 풍천면 도청대로 455', '경북'],
    ['경상남도 창원시 의창구 중앙대로 300', '경남'],
    ['대구광역시 북구 연암로 40', '대구'],
    ['울산광역시 남구 중앙로 201', '울산'],
    ['부산광역시 연제구 중앙대로 1001', '부산'],
    ['제주특별자치도 제주시 문연로 6', '제주'],
  ])('현재 행정구역 명칭 %s를 %s로 판별한다', (address, region) => {
    expect(regionOf(address)).toBe(region)
  })

  it.each([
    ['강원도 춘천시 중앙로 1', '강원'],
    ['전라북도 전주시 완산구 효자로 225', '전북'],
    ['제주도 제주시 문연로 6', '제주'],
  ])('바뀌기 전 명칭 %s를 %s로 판별한다', (address, region) => {
    expect(regionOf(address)).toBe(region)
  })

  it.each([
    ['서울 중구 세종대로 110', '서울'],
    ['강원 춘천시 중앙로 1', '강원'],
    ['세종 한누리대로 2130', '세종'],
    ['전북 전주시 완산구 효자로 225', '전북'],
    ['제주 제주시 문연로 6', '제주'],
    ['  경기   수원시 팔달구 효원로 1', '경기'],
  ])('줄임 명칭 %s를 %s로 판별한다', (address, region) => {
    expect(regionOf(address)).toBe(region)
  })

  it.each([
    '',
    '강남구 테헤란로 152',
    '서울특별시중구 세종대로',
    'constructor',
  ])('시/도로 시작하지 않는 주소 "%s"는 판별하지 않는다', (address) => {
    expect(regionOf(address)).toBeUndefined()
  })
})
